## OP MATEMÁTICOS ##

# VARIAVEIS BASE
a = float(input("DIGITE O PRIMEIRO NÚMERO: "))
b = float(input("DIGITE O SEGUNDO NÚMERO: "))

# OPERAÇÃO DE ADICÃO
print("ADIÇÃO")
print(f"A soma de {a} + {b} é: ", a + b, "\n")

# OPERAÇÃO DE SUBTRAÇÃO
print("SUBTRAÇÃO")
print(f"A subtração de {a} - {b} é: ", a - b, "\n")

# OPERAÇÃO DE SUBTRAÇÃO
print("MULTIPLICAÇÃO")
print(f"A multiplicação de {a} x {b} é: ", a * b, "\n")

# OPERAÇÃO DE DIVISÃO
print("DIVISÃO")
print(f"A divisão de {a} / {b} é: ", a / b, "\n")
print(f"A divisão de {a} // {b} é: ", a // b, "\n")

# OPERAÇÃO DE MÓDULO DA DIVISÃO
print("MÓDULO")
print(f"O módulo de {a} % {b} é: ", a % b, "\n")

# OPERAÇÃO DE POTENCIAÇÃO
print("POTENCIAÇÃO")
print(f"A potenciação de {a} ** {b} é: ", a ** b)